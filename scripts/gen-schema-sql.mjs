// Writes the database schema as SQL into src/lib/schema-sql.ts, so the app can
// create its tables at startup on hosts where `prisma db push` cannot run
// (for example Vercel, where only /tmp is writable). Run by `npm run build`.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const sql = execFileSync("npx", ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", "prisma/schema.prisma", "--script"], {
  encoding: "utf8",
  env: { ...process.env, DATABASE_URL: process.env.DATABASE_URL ?? "file:./dev.db" },
});

const statements = sql
  .split(";")
  .map((s) => s.replace(/^\s*--.*$/gm, "").trim())
  .filter(Boolean)
  .map((s) => s.replace(/^CREATE TABLE /, "CREATE TABLE IF NOT EXISTS ").replace(/^CREATE (UNIQUE )?INDEX /, "CREATE $1INDEX IF NOT EXISTS "));

writeFileSync(
  "src/lib/schema-sql.ts",
  `// Generated by scripts/gen-schema-sql.mjs from prisma/schema.prisma. Do not edit.\nexport const SCHEMA_STATEMENTS: string[] = ${JSON.stringify(statements, null, 2)};\n`,
);
console.log(`schema-sql.ts: ${statements.length} statements`);
